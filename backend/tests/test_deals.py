"""Deals: CRUD, how a deal is priced, and the stage transition.

There was nowhere to record that a conversation became an opportunity. These
tests pin the replacement, and they cluster around the two things that are not
plain CRUD:

*Value is not one number.* A fixed-price bid has a contract sum; an engagement
billed per day worked has a rate and possibly no end at all. `expected_value` is
generated by Postgres from whichever shape applies, and is **NULL, never 0**,
when no total can be derived — because summing open-ended deals as zero is how a
day-rate-heavy pipeline reads as empty.

*A stage is not a label.* Arriving in a decided stage stamps `closed_at`, pins
the probability to 100 or 0, and decides whether a lost reason may exist at all.
Winning does not finish the work, so `running` and `completed` sit after `won`.
PATCH has to apply exactly the same rules as the stage endpoint, or a deal's
history depends on which button was pressed.
"""

from typing import Any

from httpx2 import AsyncClient

from tests.conftest import Account, create_resource


async def _deal(client: AsyncClient, account: Account, **fields: Any) -> dict[str, Any]:
    payload: dict[str, Any] = {"title": "Website relaunch"}
    payload.update(fields)
    return await create_resource(client, account, "/deals/", payload)


async def test_a_deal_survives_a_full_round_trip(client: AsyncClient, alice: Account) -> None:
    created = await _deal(
        client,
        alice,
        title="Website relaunch",
        fixed_value="12500.00",
        currency="EUR",
        stage="proposal",
        expected_close_date="2026-11-30",
        probability=60,
        notes="Waiting on their design sign-off.",
    )
    assert created["fixed_value"] == "12500.00"
    assert created["expected_value"] == "12500.00"
    assert created["currency"] == "EUR"
    assert created["stage"] == "proposal"
    assert created["expected_close_date"] == "2026-11-30"
    assert created["probability"] == 60
    assert created["is_open"] is True
    assert created["closed_at"] is None

    fetched = await client.get(f"/deals/{created['id']}", headers=alice.headers)
    assert fetched.status_code == 200
    assert fetched.json()["notes"] == "Waiting on their design sign-off."

    patched = await client.patch(
        f"/deals/{created['id']}", json={"fixed_value": "14000.00"}, headers=alice.headers
    )
    assert patched.status_code == 200
    assert patched.json()["fixed_value"] == "14000.00"
    # The generated column followed the edit.
    assert patched.json()["expected_value"] == "14000.00"
    assert patched.json()["title"] == "Website relaunch"

    deleted = await client.delete(f"/deals/{created['id']}", headers=alice.headers)
    assert deleted.status_code == 204
    assert (await client.get(f"/deals/{created['id']}", headers=alice.headers)).status_code == 404


