async def test_winning_a_deal_closes_it_at_full_probability(
    client: AsyncClient, alice: Account
) -> None:
    deal = await _deal(client, alice, stage="negotiation", probability=70)

    response = await client.post(
        f"/deals/{deal['id']}/stage", json={"stage": "won"}, headers=alice.headers
    )

    assert response.status_code == 200
    won = response.json()
    assert won["stage"] == "won"
    assert won["is_open"] is False
    assert won["is_won"] is True
    assert won["closed_at"] is not None
    # Banked money must stop being forecast at 70%.
    assert won["probability"] == 100
    assert won["lost_reason"] is None


async def test_a_won_deal_stays_on_the_board_while_the_work_runs(
    client: AsyncClient, alice: Account
) -> None:
    # Winning an engagement billed by the day *starts* it. Without somewhere for
    # "won and running" to sit, every long engagement would leave the board the
    # day the work began.
    deal = await _deal(
        client, alice, value_type="rate_based", rate="800.00", rate_unit="day", stage="negotiation"
    )
    await client.post(f"/deals/{deal['id']}/stage", json={"stage": "won"}, headers=alice.headers)

    running = await client.post(
        f"/deals/{deal['id']}/stage", json={"stage": "running"}, headers=alice.headers
    )
    assert running.json()["is_active"] is True
    assert running.json()["is_won"] is True
    assert running.json()["is_open"] is False

    completed = await client.post(
        f"/deals/{deal['id']}/stage", json={"stage": "completed"}, headers=alice.headers
    )
    # Finished: still won, but off the board.
    assert completed.json()["is_won"] is True
    assert completed.json()["is_active"] is False


async def test_starting_and_finishing_the_work_does_not_move_the_date_it_was_won_on(
    client: AsyncClient, alice: Account
) -> None:
    # closed_at is when the deal was *decided*, not when the work ended.
    deal = await _deal(client, alice)
    won = await client.post(
        f"/deals/{deal['id']}/stage", json={"stage": "won"}, headers=alice.headers
    )
    closed_at = won.json()["closed_at"]

    for stage in ("running", "completed"):
        moved = await client.post(
            f"/deals/{deal['id']}/stage", json={"stage": stage}, headers=alice.headers
        )
        assert moved.json()["closed_at"] == closed_at, f"{stage} moved the close date"

    # Nor does a plain edit, or re-sending the stage it is already in.
    edited = await client.patch(
        f"/deals/{deal['id']}", json={"title": "Phase 1"}, headers=alice.headers
    )
    assert edited.json()["closed_at"] == closed_at


async def test_changing_the_decision_does_restamp_the_close(
    client: AsyncClient, alice: Account
) -> None:
    deal = await _deal(client, alice)
    won = await client.post(
        f"/deals/{deal['id']}/stage", json={"stage": "won"}, headers=alice.headers
    )

    lost = await client.post(
        f"/deals/{deal['id']}/stage", json={"stage": "lost"}, headers=alice.headers
    )

    # Going from won to lost is a new decision, not a step through delivery.
    assert lost.json()["closed_at"] != won.json()["closed_at"]
    assert lost.json()["probability"] == 0


